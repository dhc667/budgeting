export type IconName = keyof typeof icons;

export const iconNames = Object.keys(icons).filter(isIconName);

function isIconName(name: string): name is IconName {
  return Object.hasOwn(icons, name);
}

// A category may name an icon this version of the app doesn't offer.
export function iconFor(name: string): LucideIcon {
  return isIconName(name) ? icons[name].Icon : CircleQuestionMark;
}

export function iconLabel(name: IconName, t: TFunction): string {
  return icons[name].label(t);
}
